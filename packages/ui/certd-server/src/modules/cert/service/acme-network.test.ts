import assert from "node:assert/strict";
import { isPublicIp } from "./acme-network.js";

describe("ACME HTTP-01 network guard", () => {
  it("拒绝私网、回环、链路本地、组播和保留地址", () => {
    const blocked = [
      "0.0.0.0",
      "10.0.0.1",
      "100.64.0.1",
      "127.0.0.1",
      "169.254.1.1",
      "172.16.0.1",
      "172.31.255.254",
      "192.0.0.1",
      "192.0.2.1",
      "192.168.1.1",
      "198.18.0.1",
      "198.51.100.1",
      "203.0.113.1",
      "224.0.0.1",
      "255.255.255.255",
      "::",
      "::1",
      "fe80::1",
      "fc00::1",
      "fd00::1",
      "ff02::1",
      "2001:db8::1",
      "fec0::1",
      "2002::1",
      "64:ff9b::1",
      "100::1",
      "2001:2::1",
      "::ffff:127.0.0.1",
      "::10.0.0.1",
    ];
    for (const ip of blocked) {
      assert.equal(isPublicIp(ip), false, `${ip} 应被拒绝`);
    }
  });

  it("允许公网 IPv4/IPv6 地址", () => {
    for (const ip of ["8.8.8.8", "1.1.1.1", "2606:4700:4700::1111", "2001:4860:4860::8888"]) {
      assert.equal(isPublicIp(ip), true, `${ip} 应被允许`);
    }
  });
});
